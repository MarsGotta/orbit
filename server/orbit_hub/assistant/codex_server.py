"""Codex app-server v2 sessions, turns, activity and human callbacks.

Protocol checked against schemas generated by codex-cli 0.164.0. Auth stays
inside the CLI under CODEX_HOME; no account token is requested or parsed.
"""

import asyncio
import base64

from ..errors import HubError
from .agent_config import instructions_text
from .backend import ActivityItem, ImageBlock, MessageChunk, PlanStep, StatusNotice, TextBlock
from .codex_policy import thread_config
from .codex_rpc import MAX_SERVER_REQUESTS, CodexRpc, RpcError
from .deletion import command_deletion
from .official_tools import OPEN_TIMEOUT_SECONDS, VendorProcess


class CodexProcess(VendorProcess):
    async def open(self):
        self.turn_id = None
        self.finished = None
        self.turn_ready = asyncio.Event()
        self.rate_info = {}
        self.host_items = {}
        self.rpc = CodexRpc(self.backend, self.notification, self.server_request, self.jail_prefix)
        try:
            await self.rpc.open()
            # This endpoint returns only safe account metadata (type, email,
            # plan), never credentials. Renewal stays in Codex itself.
            account = await self.rpc.call("account/read", {"refreshToken": False})
            if "account" in account:
                self.account(account["account"])
            params = {
                "cwd": str(self.workspace),
                "approvalPolicy": "untrusted",
                "approvalsReviewer": "user",
                "sandbox": "danger-full-access",
                "developerInstructions": instructions_text(self.backend.instructions()) or "",
                "config": {
                    **thread_config(self.workspace),
                    # The outer jail is the only kernel sandbox. Codex cannot
                    # create a nested bwrap namespace under Ubuntu AppArmor.
                    # Replace the map, including any servers in CODEX_HOME.
                    "mcp_servers": {"orbit": {**self.backend.mcp_server(), "required": True}},
                },
            }
            if self.resuming:
                params["threadId"] = self.session_id
                params["excludeTurns"] = True
            answer = await self.rpc.call(
                "thread/resume" if self.resuming else "thread/start", params, OPEN_TIMEOUT_SECONDS
            )
            session_id = answer["thread"]["id"]
            if not isinstance(session_id, str) or not session_id:
                raise ValueError
            if self.resuming and session_id != self.session_id:
                raise ValueError
            self.session_id = session_id
            self.interactions.session_id = session_id
        except RpcError as exc:
            raise self.rpc_failure(exc) from None
        except (KeyError, TypeError, ValueError):
            raise self.refusal("agent_protocol", "did not return its conversation ID") from None

    def start_turn(self, blocks):
        if self.turn is not None:
            raise self.refusal("turn_in_progress", "already has a turn in progress")
        self.turn_ready.clear()
        self.host_items.clear()
        self.turn_id = None
        super().start_turn(blocks)
        self.rate_limit(self.rate_info)

    async def execute(self, blocks):
        self.finished = asyncio.get_running_loop().create_future()
        content = []
        for block in blocks:
            if isinstance(block, TextBlock):
                content.append({"type": "text", "text": block.text, "text_elements": []})
            elif isinstance(block, ImageBlock):
                data = base64.b64encode(block.data).decode()
                content.append({"type": "image", "url": f"data:{block.mime};base64,{data}"})
        try:
            answer = await self.rpc.call(
                "turn/start", {"threadId": self.session_id, "input": content}
            )
            self.turn_id = answer["turn"]["id"]
            self.turn_ready.set()
            return self.result(await self.finished)
        except RpcError as exc:
            raise self.rpc_failure(exc) from None
        finally:
            self.turn_ready.set()
            if not self.finished.done():
                self.finished.cancel()

    def rpc_failure(self, error):
        info = error.data if isinstance(error.data, dict) else {}
        mark = info.get("codexErrorInfo")
        if mark == "usageLimitExceeded":
            return self.limit_failure()
        if mark == "unauthorized":
            return self.auth_failure()
        numbers = {"rpc_code": error.code} if type(error.code) is int else None
        return self.refusal("agent_rejected", "refused an Orbit request", numbers)

    def result(self, turn):
        status = turn.get("status")
        if status in {"completed", "interrupted"}:
            return status
        error = turn.get("error") or {}
        mark = error.get("codexErrorInfo")
        details = {}
        if isinstance(mark, dict) and len(mark) == 1:
            mark, details = next(iter(mark.items()))
            details = details if isinstance(details, dict) else {}
        if mark == "usageLimitExceeded":
            raise self.limit_failure()
        if mark == "unauthorized":
            raise self.auth_failure()
        # Refusals name their structured cause, never raw diagnostic text.
        causes = {
            "contextWindowExceeded": "exhausted its context window",
            "rateLimitExceeded": "received too many requests",
            "sessionBudgetExceeded": "exhausted the session budget",
            "sandboxError": "could not execute inside its sandbox",
            "flexUnavailable": "has no Flex capacity available",
            "serverOverloaded": "reported that the service is overloaded",
            "cyberPolicy": "refused the turn under its cybersecurity policy",
            "misalignmentPolicyViolation": "refused the turn under its safety policy",
            "tooManyDenials": "stopped after too many denials",
            "internalServerError": "reported an internal Codex failure",
            "badRequest": "refused the request format",
            "threadRollbackFailed": "could not restore thread state",
            "httpConnectionFailed": "could not connect to the provider after retrying",
            "httpResponseStreamConnectionFailed": "could not open the provider response",
            "responseStreamDisconnected": "lost the provider response connection",
            "responseStreamLimitExceeded": "exhausted provider response retries",
        }
        known = mark if isinstance(mark, str) and mark in causes else None
        numbers = {"stop_reason": known} if known else {}
        if known and type(details.get("httpStatusCode")) is int:
            numbers["http_status_code"] = details["httpStatusCode"]
        raise self.refusal(
            "agent_rejected",
            causes[known] if known else "did not report the structured failure cause",
            numbers or None,
        )

    async def notification(self, method, params):
        if method == "orbit/transportClosed":
            if self.finished is not None and not self.finished.done():
                self.finished.set_exception(self.rpc.failure)
            self.connection.forget(self)
            return
        if method == "account/rateLimits/updated":
            self.rate_limit(params.get("rateLimits", {}))
            return
        if method == "account/updated":
            if "authMode" in params and params["authMode"] is None:
                self.backend.observe("auth_required")
            return
        if self.turn is None or params.get("threadId") != self.session_id:
            return
        if method == "error" and params.get("willRetry") is True:
            await self.connection.emit(
                StatusNotice(
                    self.session_id, "retrying_openai", "OpenAI tarda en contestar; reintentando"
                )
            )
        elif method == "item/agentMessage/delta":
            text = params.get("delta")
            if isinstance(text, str):
                self.text.append(text)
                await self.connection.emit(MessageChunk(self.session_id, text))
        elif method == "turn/completed":
            if self.finished is not None and not self.finished.done():
                self.finished.set_result(params["turn"])
        elif method in {"item/started", "item/completed"}:
            await self.item(params["item"], method == "item/completed")
        elif method == "turn/plan/updated":
            steps = tuple(PlanStep(p["step"], p["status"]) for p in params.get("plan", []))
            phase = (
                "completed" if steps and all(s.status == "completed" for s in steps) else "progress"
            )
            await self.connection.emit(
                ActivityItem(self.session_id, "plan", "plan", phase, steps=steps)
            )

    async def item(self, item, completed):
        kind = item.get("type")
        if kind == "fileChange":
            if completed:
                self.host_items.pop(item["id"], None)
            else:
                # Retain only files awaiting completion/approval, bounded by
                # the same callback ceiling as the RPC transport.
                if len(self.host_items) >= MAX_SERVER_REQUESTS:
                    raise HubError("agent_protocol", "Codex exceeded 16 simultaneous edits")
                self.host_items[item["id"]] = item
        phase = "completed" if completed else "started"
        if item.get("status") in {"failed", "declined"}:
            phase = "failed"
        if kind in {"mcpToolCall", "commandExecution", "fileChange"}:
            name = item.get("tool") or {"commandExecution": "command", "fileChange": "edit"}.get(
                kind
            )
            arguments = item.get("arguments")
            if kind == "commandExecution":
                arguments = {"command": item.get("command"), "cwd": item.get("cwd")}
            elif kind == "fileChange":
                arguments = {"paths": [change.get("path") for change in item.get("changes", [])]}
            await self.connection.emit(
                ActivityItem(
                    self.session_id,
                    item["id"],
                    "tool",
                    phase,
                    name,
                    arguments if isinstance(arguments, dict) else None,
                    cause="The tool failed" if phase == "failed" else None,
                    cause_code="tool_failed" if phase == "failed" else None,
                )
            )
        elif kind == "reasoning":
            await self.connection.emit(
                ActivityItem(
                    self.session_id,
                    item["id"],
                    "reasoning",
                    phase,
                    text=" ".join(item.get("summary", [])),
                )
            )

    def rate_limit(self, info):
        self.rate_info = info
        windows = [info.get(key) for key in ("primary", "secondary")]
        windows = [w for w in windows if isinstance(w, dict) and type(w.get("usedPercent")) is int]
        if not windows:
            return
        window = max(windows, key=lambda w: (w["usedPercent"], w.get("resetsAt") or 0))
        reset = window.get("resetsAt")
        reset_ms = reset * 1000 if type(reset) is int else None
        used = window.get("usedPercent")
        if type(used) is int and 0 <= used <= 100:
            if used >= 100:
                self.limit_resets_ms = reset_ms
            duration = window.get("windowDurationMins")
            self.backend.observe(
                "usage",
                used_percent=used,
                window=f"{duration} min" if type(duration) is int else None,
                resets_at_ms=reset_ms,
            )

    def account(self, account):
        if account is None:
            self.backend.observe("auth_required")
        elif isinstance(account, dict):
            # Bound the published labels, not a token or an auth response.
            # 128-byte email and 64-byte plan fit the status topic even for
            # all 32 agents; overlong labels are absent rather than truncated.
            def label(key, ceiling):
                text = account.get(key)
                return (
                    text
                    if isinstance(text, str)
                    and text.isprintable()
                    and len(text.encode()) <= ceiling
                    else None
                )

            self.backend.observe(
                "status", kind="account", email=label("email", 128), plan=label("planType", 64)
            )

    async def server_request(self, method, params):
        if params.get("threadId") != self.session_id or self.turn is None:
            raise HubError("agent_protocol", "Codex requested an action outside its turn")
        if method in {"item/commandExecution/requestApproval", "item/fileChange/requestApproval"}:
            command = params.get("command") or ""
            if method == "item/commandExecution/requestApproval" and not command:
                return {"decision": "decline"}
            reason = params.get("reason") or ""
            description = (
                f"Ejecutar: {command}. {reason}"
                if command
                else "Editar archivos: "
                + ", ".join(
                    change.get("path", "")
                    for change in self.host_items.get(params.get("itemId"), {}).get("changes", [])
                )
                + f". {reason}"
            )
            arguments = {**params, "item": self.host_items.get(params.get("itemId"), {})}
            # A file approval must name its files in the card.
            if method == "item/fileChange/requestApproval" and not arguments["item"]:
                return {"decision": "decline"}
            choice = await self.interactions.permission(description, command_deletion(command))
            return {"decision": "accept" if choice == "once" else "decline"}
        if method == "item/tool/requestUserInput":
            questions = [q for q in params.get("questions", []) if not q.get("isSecret")]
            if len(questions) != len(params.get("questions", [])):
                return {"answers": {}}
            answers = await self.interactions.clarify(questions)
            return {"answers": {qid: {"answers": [text]} for qid, text in answers.items()}}
        # OAuth refresh requests and unknown extensions are never fulfilled by
        # reading account files. Only the official CLI owns account renewal.
        raise HubError("agent_protocol", "Orbit does not offer that Codex request")

    async def cancel(self):
        if self.turn is None:
            return
        await self.turn_ready.wait()
        if self.turn_id is not None and self.turn is not None:
            await self.rpc.call(
                "turn/interrupt", {"threadId": self.session_id, "turnId": self.turn_id}
            )
        await self.interactions.expire()

    async def stop(self):
        await super().stop()
        if hasattr(self, "rpc"):
            await self.rpc.close()
