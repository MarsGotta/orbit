def thread_config(workspace):
    work = Path(workspace).resolve()
    features = {**dict.fromkeys(ENABLED, True), **dict.fromkeys(DISABLED, False)}
    return {
        "features": features,
        "web_search": "disabled",
        "notify": [],
        # Explicit untrusted entries win before repo-root fallback in the
        # pinned loader. Cover all ancestors so an old trusted repo entry
        # cannot activate any parent .codex config, hooks or exec policies.
        "projects": {str(p): {"trust_level": "untrusted"} for p in (work, *work.parents)},
    }


def startup_arguments(workspace):
    # App-server initializes plugins before thread/start. Apply the same
    # policy at process startup, including the project trust lookup.
    return [
        part
        for key, value in thread_config(workspace).items()
        for part in ("-c", f"{key}={toml_value(value)}")
    ]


def toml_value(value):
    if isinstance(value, dict):
        return "{" + ", ".join(f"{json.dumps(k)} = {toml_value(v)}" for k, v in value.items()) + "}"
    return json.dumps(value)
