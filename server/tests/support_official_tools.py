def codex():
    thread = str(uuid4())
    turn = str(uuid4())
    waiting = None
    server = None

    def notify(method, **params):
        if method == "item/started":
            params["startedAtMs"] = 1000
        if method == "item/completed":
            params["completedAtMs"] = 1001
        send({"method": method, "params": {"threadId": thread, "turnId": turn, **params}})

    def end(status="completed", error=None):
        notify("turn/completed", turn={"id": turn, "status": status, "error": error, "items": []})

    for line in sys.stdin:
        msg = json.loads(line)
        method = msg.get("method")
        params = msg.get("params", {})
        if method == "initialize":
            marker = Path(os.environ["ORBIT_TOOL_RECORD"]).with_name("hold-start")
            while marker.exists():
                time.sleep(0.01)
            send(
                {
                    "id": msg["id"],
                    "result": {
                        "userAgent": "fixture",
                        "codexHome": os.environ["CODEX_HOME"],
                        "platformOs": "linux",
                        "platformFamily": "unix",
                    },
                }
            )
        elif method == "account/read":
            assert params == {"refreshToken": False}
            send(
                {
                    "id": msg["id"],
                    "result": {
                        "account": {
                            "type": "chatgpt",
                            "email": "alex@example.test",
                            "planType": "plus",
                        },
                        "requiresOpenaiAuth": True,
                    },
                }
            )
        elif method in ("thread/start", "thread/resume"):
            record({"method": method, "params": params})
            actions.codex_extensions(params["config"], record, method)
            thread = params.get("threadId", thread)
            server = params["config"]["mcp_servers"]["orbit"]
            send(
                {
                    "id": msg["id"],
                    "result": {
                        "thread": {
                            "id": thread,
                            "sessionId": thread,
                            "turns": [],
                            "cliVersion": "0.164.0",
                            "createdAt": 1000,
                            "updatedAt": 1001,
                            "cwd": os.getcwd(),
                            "ephemeral": False,
                            "modelProvider": "openai",
                            "preview": "",
                            "projectId": None,
                            "source": "appServer",
                            "status": {"type": "idle"},
                        },
                        "approvalPolicy": "on-request",
                        "approvalsReviewer": "user",
                        "cwd": os.getcwd(),
                        "model": "fixture-model",
                        "modelProvider": "openai",
                        "sandbox": {"type": "readOnly"},
                    },
                }
            )
        elif method == "turn/start":
            record({"method": method, "params": params})
            if "RPCERROR" in str(params["input"]):
                send({"id": msg["id"], "error": {"code": -32602, "message": SECRET}})
                continue
            send(
                {
                    "id": msg["id"],
                    "result": {"turn": {"id": turn, "status": "inProgress", "items": []}},
                }
            )
            text = str(params["input"])
            if broken_output(text):
                continue
            if "CAPACITY" in text:
                end("failed", {"message": SECRET, "codexErrorInfo": "serverOverloaded"})
                continue
            if "NETWORK" in text:
                end(
                    "failed",
                    {
                        "message": SECRET,
                        "codexErrorInfo": {"httpConnectionFailed": {"httpStatusCode": 503}},
                    },
                )
                continue
            if "LIMIT" in text:
                notify(
                    "account/rateLimits/updated",
                    rateLimits={
                        "primary": {
                            "usedPercent": 100,
                            "windowDurationMins": 300,
                            "resetsAt": 1900000000,
                        }
                    },
                )
                end("failed", {"message": SECRET, "codexErrorInfo": "usageLimitExceeded"})
                continue
            if "AUTH" in text:
                end("failed", {"message": SECRET, "codexErrorInfo": "unauthorized"})
                continue
            notify("item/agentMessage/delta", itemId="text-1", delta="Hola. ")
            if "SILENT" in text:
                silent_interval()
                notify("item/agentMessage/delta", itemId="text-1", delta="Hecho.")
                end()
                continue
            if "RETRY" in text:
                notify(
                    "error",
                    willRetry=True,
                    error={"message": SECRET, "codexErrorInfo": "serverOverloaded"},
                )
            if "WAIT" in text:
                continue
            if "ACTION" in text:
                waiting = "host"
                host_item = actions.codex_start(send, notify, thread, turn)
                continue
            asyncio.run(orbit_tool(server))
            item = {
                "id": "orbit-1",
                "type": "mcpToolCall",
                "server": "orbit",
                "tool": "orbit_devices",
                "arguments": {},
                "status": "inProgress",
            }
            notify("item/started", item=item)
            notify("item/completed", item={**item, "status": "completed"})
            waiting = "edit" if "EDIT" in text else "command"
            host_item = actions.codex_legacy_item(waiting)
            notify("item/started", item=host_item)
            send(
                {
                    "id": "permission-1",
                    "method": "item/fileChange/requestApproval"
                    if waiting == "edit"
                    else "item/commandExecution/requestApproval",
                    "params": {
                        "threadId": thread,
                        "turnId": turn,
                        "itemId": "command-1",
                        "command": "echo fixture",
                        "startedAtMs": 1000,
                    },
                }
            )
        elif method == "turn/interrupt":
            send({"id": msg["id"], "result": {}})
            end("interrupted")
        elif method is None and "id" in msg:
            record({"codex_response": msg})
            if waiting == "host":
                actions.codex_end(record, notify, host_item, msg["result"]["decision"] == "accept")
                end()
            elif waiting in ("command", "edit"):
                notify(
                    "item/completed",
                    item={
                        **host_item,
                        "status": "completed"
                        if msg["result"]["decision"] == "accept"
                        else "declined",
                    },
                )
                waiting = "question"
                send(
                    {
                        "id": "question-1",
                        "method": "item/tool/requestUserInput",
                        "params": {
                            "threadId": thread,
                            "turnId": turn,
                            "itemId": "question-1",
                            "isBlocking": True,
                            "questions": [
                                {
                                    "id": "where",
                                    "header": "Destino",
                                    "question": "¿Dónde?",
                                    "options": [
                                        {"label": "Jardín", "description": "Al aire libre"}
                                    ],
                                }
                            ],
                        },
                    }
                )
            else:
                notify("item/agentMessage/delta", itemId="text-1", delta="Hecho.")
                end()


def silent_interval():
    # The test advances the hub clock while the fake cannot emit any frames.
    # Only this explicit release permits the provider's final answer.
    release = Path(os.environ["ORBIT_TOOL_RECORD"]).with_name("release-silent-turn")
    while not release.exists():
        time.sleep(0.01)


def broken_output(text):
    if "CRASH" in text:
        sys.exit(7)
    if "MALFORMED" in text:
        print("{broken " + SECRET, flush=True)
        return True
    if "OVERSIZE" in text:
        from orbit_hub.assistant.official_tools import MAX_AGENT_MESSAGE_BYTES

        print(json.dumps({"ignored": "x" * (MAX_AGENT_MESSAGE_BYTES + 1)}), flush=True)
        return True
    return False


