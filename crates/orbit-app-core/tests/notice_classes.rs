//! Writes `bridge/generated/noticeClasses.ts` (not `noticeClass.ts`: it would
//! differ from `NoticeClass.ts` only in case, one file on macOS): the class of every notice code,
//! from the one table in `orbit_core::notice` (SIM-21). The interface's
//! catalogue is typed against it, so `tsc` refuses a code without an entry
//! or an entry whose class disagrees. Like the ts-rs files next to it, it is
//! committed as this test writes it and the gate checks it is up to date.
use orbit_core::notice::NoticeCode;

const TARGET: &str = "../../apps/desktop/src/bridge/generated/noticeClasses.ts";

fn render() -> String {
    let mut out = String::from(
        "// Generated by orbit-app-core's tests (tests/notice_classes.rs) from \
         orbit_core::notice::NoticeCode. Do not edit this file manually.\n\
         import type { NoticeClass } from \"./NoticeClass\";\n\
         import type { NoticeCode } from \"./NoticeCode\";\n\n\
         export const noticeClass = {\n",
    );
    for code in NoticeCode::ALL {
        let class = serde_json::to_value(code.class()).unwrap_or_default();
        out.push_str(&format!(
            "  {}: \"{}\",\n",
            code.name(),
            class.as_str().unwrap_or_default()
        ));
    }
    out.push_str("} as const satisfies Record<NoticeCode, NoticeClass>;\n");
    out
}

#[test]
fn notice_classes_are_written_for_the_interface() -> std::io::Result<()> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(TARGET);
    let rendered = render();
    if std::fs::read_to_string(&path).ok().as_deref() != Some(rendered.as_str()) {
        std::fs::write(&path, rendered)?;
    }
    // The class type itself: no exported type reaches it otherwise.
    <orbit_core::notice::NoticeClass as ts_rs::TS>::export_all()
        .map_err(|error| std::io::Error::other(error.to_string()))
}

#[test]
fn every_code_has_one_name() {
    let mut names: Vec<String> = NoticeCode::ALL.iter().map(|code| code.name()).collect();
    assert!(names.iter().all(|name| !name.is_empty()));
    names.sort();
    names.dedup();
    assert_eq!(names.len(), NoticeCode::ALL.len());
}
