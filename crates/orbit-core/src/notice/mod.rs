//! Typed notices: what Orbit tells the person, as a code and closed data.
//!
//! The daemon and this crate used to write Spanish sentences for the screen,
//! so the screen narrated internal steps and an unforeseen failure could go
//! unsaid. A notice is now a
//! [`NoticeCode`], the [`Op`] of the action it belongs to and [`NoticeData`]
//! that only admits numbers, booleans and short ASCII tokens: no type here can
//! carry the content of a meeting, a conversation or an event. The interface
//! turns the code into words through its one catalogue; the daemon writes the
//! same notice to its local report log.
//!
//! Pure: no clocks, files or randomness. An [`Op`] is parsed here and
//! generated by the processes that have a source of randomness.
//!
//! Each domain declares its own codes, with their class and what they mean,
//! in its own file below; what they all share (the class, the data, the log
//! and the report line) is here and in `data` and `log`. A new code goes in
//! its domain's file with the next free place (see `catalogue`); a notice
//! about Orbit's own processes, their supervision included, goes in `app`.
//!
//! Some codes in several domains are what the interface meets: failures
//! whose cause no longer reaches the screen, reported by the app so none is
//! silent. Their data is closed (a stage, a code, a cause kind), never the
//! cause's text.
