/// The four kinds of message the person can see, plus «only recorded».
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(
    feature = "ts",
    derive(ts_rs::TS),
    ts(export_to = "../../apps/desktop/src/bridge/generated/")
)]
#[serde(rename_all = "snake_case")]
pub enum NoticeClass {
    /// Something failed and the person can do something about it.
    Fixable,
    /// Something failed and the person cannot do anything: the generic
    /// message with the code of its op.
    Failed,
    /// Something is waiting or working for the person.
    Working,
    /// Something the person asked for finished.
    Done,
    /// Only recorded in the log; never shown.
    Silent,
}

/// The end of the chain: every domain's codes become the one wire enum. Each
/// entry is `Variant = place => Class,`; the chain starts with the enum's docs.
macro_rules! notice_catalogue {
    ([] ; docs [$($line:literal),*] $($(#[$doc:meta])* $variant:ident = $place:literal => $class:ident,)*) => {
        $(#[doc = $line])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize)]
        #[serde(rename_all = "snake_case")]
        pub enum NoticeCode {
            $($(#[$doc])* $variant = $place,)*
            /// A code this build does not know: a newer daemon said it. It
            /// reaches the person as the generic failure with its op; the
            /// daemon that said it logged the real code. Read by the
            /// `Deserialize` below, which maps every unknown name here.
            /// Always the last place, whatever the codes after this build.
            Unknown = 65_535,
        }
        wire_order!(NoticeCode { $($variant,)* Unknown });
        ts_union!(NoticeCode, [$($line),*]);

        impl NoticeCode {
            pub const fn class(self) -> NoticeClass {
                match self {
                    $(Self::$variant => NoticeClass::$class,)*
                    Self::Unknown => NoticeClass::Failed,
                }
            }
        }
    };
}

