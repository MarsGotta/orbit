"""The size limits of scripts/check/sizes.py: what is measured, how, and the ratchet.

The real repository is checked by the gate's own step (`guards-sizes`); these
tests fix the rules on small invented trees.
"""

import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "check"))

import sizes


def write(root: Path, relative: str, text: str) -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(text).lstrip("\n"), encoding="utf-8")


RUST_LIB = """
//! A crate of the tree.
mod store;
#[cfg(test)]
mod store_tests;
#[path = "elsewhere/wire.rs"]
mod wire;
"""

RUST_STORE = """
/// Opens the store.
pub struct Store;

impl Store {
    // A comment line.

    pub fn open(path: &str) -> Self {
        let braces = "}}{{";
        let quote = '{';
        let raw = r#"fn fake() { "#;
        let _ = (braces, quote, raw, path);
        Store
    }
}

impl std::fmt::Display for Store {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        fn inner() -> u8 {
            1
        }
        write!(f, "{}", inner())
    }
}

trait Named {
    fn name(&self) -> String;
    fn shout(&self) -> String {
        self.name()
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn opens() {
        let _ = super::Store::open("x");
    }
}
"""


class RustMeasurementTests(unittest.TestCase):
    def measure(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            write(root, "crates/demo/Cargo.toml", "[package]\nname = 'demo'\n")
            write(root, "crates/demo/src/lib.rs", RUST_LIB)
            write(root, "crates/demo/src/store.rs", RUST_STORE)
            write(root, "crates/demo/src/store_tests.rs", "fn a() {}\n" * 600)
            write(root, "crates/demo/src/elsewhere/wire.rs", "pub fn wire() {}\n")
            write(root, "crates/demo/tests/integration.rs", "fn b() {}\n" * 600)
            return sizes.measure(root)

    def test_only_files_built_outside_tests_are_measured(self):
        measured = self.measure()
        self.assertEqual(
            sorted(measured.files),
            [
                "crates/demo/src/elsewhere/wire.rs",
                "crates/demo/src/lib.rs",
                "crates/demo/src/store.rs",
            ],
        )

    def test_comments_blank_lines_and_test_items_do_not_count(self):
        measured = self.measure()
        # `#[cfg(test)] mod store_tests;` is two lines of test code.
        self.assertEqual(measured.files["crates/demo/src/lib.rs"], 3)
        # 24 lines of code before `#[cfg(test)] mod tests`, none of it after.
        self.assertEqual(measured.files["crates/demo/src/store.rs"], 24)

    def test_functions_run_from_their_keyword_to_their_closing_brace(self):
        functions = self.measure().functions["crates/demo/src/store.rs"]
        self.assertEqual(
            functions,
            {
                "Store::open": 7,
                "<Store as Display>::fmt": 6,
                "<Store as Display>::fmt::inner": 3,
                "Named::shout": 3,
            },
        )


class PythonMeasurementTests(unittest.TestCase):
    SOURCE = '''
    """A module docstring
    over two lines."""

    import functools


    class Hub:
        """Its docstring."""

        @functools.cache
        def open(self, name):
            # A comment.
            text = """a string
            of three
            lines"""

            def inner():
                return text

            return inner()
    '''

    def test_docstrings_and_comments_do_not_count_and_strings_do(self):
        lines, functions = sizes.measure_python_source(textwrap.dedent(self.SOURCE))
        self.assertEqual(lines, 10)
        self.assertEqual(functions, [("Hub.open", 7), ("Hub.open.inner", 2)])

    def test_tests_and_their_folders_are_not_production(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for relative in (
                "server/orbit_hub/app.py",
                "server/orbit_hub/conftest.py",
                "server/orbit_mcp/test_tools.py",
                "scripts/tests/test_guard.py",
                "scripts/tests/fixture.py",
                "scripts/release/build_test.py",
                "scripts/release/build.py",
            ):
                write(root, relative, "x = 1\n")
            write(root, "scripts/release/made.py", "# @generated by a tool\nx = 1\n")
            self.assertEqual(
                sorted(sizes.measure(root).files),
                ["scripts/release/build.py", "server/orbit_hub/app.py"],
            )


class SwiftMeasurementTests(unittest.TestCase):
    SOURCE = '''
    protocol Reader {
        func read() -> Int
        func close()
    }

    final class Host {
        /// Documented.
        init(name: String) {
            let text = "a { brace \\(name.count) and \\("}")"
            print(text)
        }

        func run() {
            let block = """
            {
            """
            print(block)
        }

        struct Inner {
            func step() {}
        }
    }
    '''

    def test_requirements_are_not_functions_and_bodies_are(self):
        lines, functions = sizes.measure_swift_source(textwrap.dedent(self.SOURCE))
        self.assertEqual(lines, 19)
        self.assertEqual(functions, [("Host.init", 4), ("Host.run", 6), ("Host.Inner.step", 1)])


def measurement(files: dict[str, int], functions: dict[str, dict[str, int]]):
    measured = sizes.Measurement()
    for path, size in files.items():
        measured.files[path] = size
        measured.language[path] = "rust"
        measured.functions[path] = dict(functions.get(path, {}))
    return measured


class RatchetTests(unittest.TestCase):
    def test_a_new_file_or_function_over_the_limit_fails_with_both_numbers(self):
        found = sizes.problems(
            measurement({"a.rs": 501}, {"a.rs": {"Runtime::run": 81}}), sizes.Ratchet()
        )
        self.assertEqual(len(found), 2)
        self.assertIn("a.rs: 501 lines of code, over the limit of 500 per file", found[0])
        self.assertIn("function `Runtime::run`: 81 lines of code, over the limit of 80", found[1])
        self.assertTrue(all("takes no new entries" in problem for problem in found))

    def test_within_the_limits_nothing_needs_an_entry(self):
        found = sizes.problems(measurement({"a.rs": 500}, {"a.rs": {"f": 80}}), sizes.Ratchet())
        self.assertEqual(found, [])

    def test_an_entry_that_grows_fails_with_both_numbers(self):
        ratchet = sizes.Ratchet({"a.rs": 900}, {"a.rs": {"f": 120}})
        found = sizes.problems(measurement({"a.rs": 901}, {"a.rs": {"f": 121}}), ratchet)
        self.assertEqual(len(found), 2)
        self.assertIn("901 lines of code, 1 more than the 900 the ratchet holds it to", found[0])
        self.assertIn("`f`: 121 lines of code, 1 more than the 120", found[1])

    def test_an_exact_entry_passes(self):
        ratchet = sizes.Ratchet({"a.rs": 900}, {"a.rs": {"f": 120}})
        self.assertEqual(
            sizes.problems(measurement({"a.rs": 900}, {"a.rs": {"f": 120}}), ratchet), []
        )

    def test_an_entry_that_shrank_must_follow_so_it_cannot_grow_back(self):
        ratchet = sizes.Ratchet({"a.rs": 900, "b.rs": 600}, {"a.rs": {"f": 120}})
        found = sizes.problems(
            measurement({"a.rs": 700, "b.rs": 400}, {"a.rs": {"f": 60}}), ratchet
        )
        self.assertEqual(
            found,
            [
                (
                    "a.rs: 700 lines of code, below the 900 the ratchet records: "
                    "lower the entry to 700 (sizes.py --shrink)."
                ),
                (
                    "b.rs: 400 lines of code, back within the limit of 500 per file: "
                    "remove its entry (600) from the ratchet (sizes.py --shrink)."
                ),
                (
                    "a.rs: function `f`: 60 lines of code, back within the limit of 80 per "
                    "function: remove its entry (120) from the ratchet (sizes.py --shrink)."
                ),
            ],
        )

    def test_an_entry_for_something_gone_fails(self):
        ratchet = sizes.Ratchet({"gone.rs": 900}, {"a.rs": {"removed": 120}})
        found = sizes.problems(measurement({"a.rs": 10}, {}), ratchet)
        self.assertEqual(len(found), 2)
        self.assertIn("gone.rs: the ratchet holds it at 900 lines", found[0])
        self.assertIn("`removed`: the ratchet holds it at 120 lines", found[1])

    def test_shrink_lowers_and_removes_but_never_adds_or_raises(self):
        ratchet = sizes.Ratchet(
            {"a.rs": 900, "b.rs": 600, "c.rs": 700}, {"a.rs": {"f": 120, "g": 100}}
        )
        measured = measurement(
            {"a.rs": 950, "b.rs": 550, "c.rs": 300, "new.rs": 800},
            {"a.rs": {"f": 130, "g": 90, "h": 200}},
        )
        shrunk = sizes.shrink(measured, ratchet)
        self.assertEqual(shrunk.files, {"a.rs": 900, "b.rs": 550})
        self.assertEqual(shrunk.functions, {"a.rs": {"f": 120, "g": 90}})

    def test_the_ratchet_round_trips_through_its_file(self):
        ratchet = sizes.Ratchet({"a b.rs": 900}, {"x.py": {'Odd."name"': 99}})
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "ratchet.toml"
            path.write_text(sizes.render_ratchet(ratchet), encoding="utf-8")
            loaded = sizes.load_ratchet(path)
        self.assertEqual((loaded.files, loaded.functions), (ratchet.files, ratchet.functions))

    def test_the_checked_in_ratchet_is_written_as_shrink_writes_it(self):
        text = sizes.RATCHET.read_text(encoding="utf-8")
        self.assertEqual(sizes.render_ratchet(sizes.load_ratchet(sizes.RATCHET)), text)


if __name__ == "__main__":
    unittest.main()
